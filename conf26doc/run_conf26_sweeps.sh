#!/usr/bin/env bash
set -euo pipefail

# Publication expert-placement sweep launcher.
# Default output root:
#   out/conf26/build/sweeps
#
# By default (--extended) this runs the FC-aligned set so HyperX can search the
# same replicated-expert-set space the FC baseline is forced into (32 disconnected
# racks => 32 complete expert sets). Four runs are produced:
#   1. generalized_ep_torus3d          - 3D torus (16x16x16) single-set EP sweep.
#   2. generalized_ep_hyperx           - HyperX single-set EP sweep (legacy /
#                                        2D MoE-TP shapes).
#   3. generalized_ep_hyperx_full_s    - HyperX DP-replicated expert sets at
#                                        s in {1,2,4,8,16,32}, then merged with (2)
#                                        into generalized_ep_hyperx_combined.csv.
#   4. fc128x32_disagg_ep_baseline     - FC128x32 disaggregated baseline (32 sets).
#
# Pass --submitted to reproduce the original submitted set: skips run (3) and the
# combined HyperX summary, leaving HyperX at single-set EP only.

EXTENDED=1
for arg in "$@"; do
  case "${arg}" in
    --extended) EXTENDED=1 ;;
    --submitted) EXTENDED=0 ;;
    -h|--help)
      echo "Usage: $0 [--extended|--submitted]"
      echo "  --extended   Run HyperX full-s sweep and build combined summary (default)."
      echo "  --submitted  Reproduce original submitted set (skip full-s extension)."
      exit 0
      ;;
    *)
      echo "Unknown argument: ${arg}" >&2
      echo "Usage: $0 [--extended|--submitted]" >&2
      exit 2
      ;;
  esac
done

HW_LIB="hardware_specs/hardware_library.yaml"
LOGICAL="conf26/topology_zoo/logical/logical_4096_tp2d_32x128_multidim.yaml"
WORKLOAD="conf26/inference_decode_specs/inference_decode_spec__conf26_decode.yaml"
MODEL="conf26/model_zoo/gpt_moe_config__1024_experts__gqa_mlp025.yaml"
OUT_DIR="out/conf26/build/sweeps"

TORUS3D_LOGICAL="conf26/topology_zoo/logical/logical_4096_tp2d_16x16x16_multidim.yaml"
TORUS3D_WORKLOAD="conf26/inference_decode_specs/inference_decode_spec__conf26_decode__torus3d.yaml"

# Torus generalized (3D torus modeled as 16x16x16 logical decomposition)
MPLCONFIGDIR=tmp/mpl_torus scalescope-cli \
  --hardware-lib "$HW_LIB" \
  --physical-topology "conf26/topology_zoo/physical/physical_4096_torus_16x16x16.yaml" \
  --logical-topology "$TORUS3D_LOGICAL" \
  --workload-spec "$TORUS3D_WORKLOAD" \
  --model-spec "$MODEL" \
  --sweep-config "conf26/sweep_configs/expert_placement_generalized_torus_3d.yaml" \
  --pass-mode inference_decode \
  --quiet \
  --output-dir "$OUT_DIR" \
  --run-name "generalized_ep_torus3d" \
  --no-timestamp --overwrite --raw-output

# HyperX generalized (single-set EP sweep, retained for legacy / 2D MoE-TP shapes).
MPLCONFIGDIR=tmp/mpl_hyperx scalescope-cli \
  --hardware-lib "$HW_LIB" \
  --physical-topology "conf26/topology_zoo/physical/physical_4096_hyperx_32x128.yaml" \
  --logical-topology "$LOGICAL" \
  --workload-spec "$WORKLOAD" \
  --model-spec "$MODEL" \
  --sweep-config "conf26/sweep_configs/expert_placement_generalized_fixed_tp.yaml" \
  --pass-mode inference_decode \
  --quiet \
  --output-dir "$OUT_DIR" \
  --run-name "generalized_ep_hyperx" \
  --no-timestamp --overwrite --raw-output

if [[ "${EXTENDED}" -eq 1 ]]; then
  # HyperX FC-style full-s sweep: DP-replicated expert sets at s in {1,2,4,8,16,32}.
  # Generated by conf26/sweep_configs/_generate_hyperx_full_s_sweep.py.
  MPLCONFIGDIR=tmp/mpl_hyperx_full_s scalescope-cli \
    --hardware-lib "$HW_LIB" \
    --physical-topology "conf26/topology_zoo/physical/physical_4096_hyperx_32x128.yaml" \
    --logical-topology "$LOGICAL" \
    --workload-spec "$WORKLOAD" \
    --model-spec "$MODEL" \
    --sweep-config "conf26/sweep_configs/expert_placement_hyperx_full_s_sweep.yaml" \
    --pass-mode inference_decode \
    --quiet \
    --output-dir "$OUT_DIR" \
    --run-name "generalized_ep_hyperx_full_s" \
    --no-timestamp --overwrite --raw-output

  # Build a combined HyperX summary (FC-style full-s sweep where available, plus
  # legacy single-set EP rows for batch sizes the full-s sweep does not cover).
  python - <<'PY'
import pandas as pd
from pathlib import Path
old = pd.read_csv("out/conf26/build/sweeps/generalized_ep_hyperx/summary.csv")
new = pd.read_csv("out/conf26/build/sweeps/generalized_ep_hyperx_full_s/summary.csv")
common = list(set(old.columns) & set(new.columns))
new_batches = set(new["batch"].unique())
keep_old = old[~old["batch"].isin(new_batches)]
combined = pd.concat([keep_old[common], new[common]], ignore_index=True)
out_path = Path("out/conf26/build/sweeps/generalized_ep_hyperx_combined.csv")
combined.to_csv(out_path, index=False)
print(f"Wrote {out_path} ({len(combined)} rows)")
PY
fi

# FC disaggregated constrained baseline
MPLCONFIGDIR=tmp/mpl_fc scalescope-cli \
  --hardware-lib "$HW_LIB" \
  --physical-topology "conf26/topology_zoo/physical/physical_4096_fc128_x32_groups.yaml" \
  --logical-topology "$LOGICAL" \
  --workload-spec "$WORKLOAD" \
  --model-spec "$MODEL" \
  --sweep-config "conf26/sweep_configs/expert_placement_fc128x32_disaggregated.yaml" \
  --pass-mode inference_decode \
  --quiet \
  --output-dir "$OUT_DIR" \
  --run-name "fc128x32_disagg_ep_baseline" \
  --no-timestamp --overwrite --raw-output
